def build_dataset() -> list[LabelledTicket]:
    tickets = [LabelledTicket(*case) for case in _CASES]
    if len(tickets) < 120 or len({ticket.text for ticket in tickets}) != len(tickets):
        raise RuntimeError("The evaluation set must contain 120 or more unique tickets.")
    return tickets
